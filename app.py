"""
Это необязательный маленький сервер на Python (на библиотеке Flask).

Он нужен только для одного: чтобы открыть сайт по адресу вида
http://localhost:5050 вместо того, чтобы открывать файл index.html
напрямую двойным щелчком. Разницы для внешнего вида сайта нет —
это просто ещё один способ его запустить.

Как запустить:
    1. Установить Flask (один раз):  pip install -r requirements.txt
    2. Запустить сервер:             python3 app.py
    3. Открыть в браузере:           http://localhost:5050
"""

from flask import Flask, send_from_directory

# Создаём приложение Flask и говорим ему: "статические файлы (css, js, картинки)
# лежат в этой же папке, что и сам app.py" — static_folder="."
app = Flask(__name__, static_folder=".", static_url_path="")


@app.get("/")
def index():
    # Когда кто-то открывает главную страницу сайта —
    # отдаём ему файл index.html из текущей папки.
    return send_from_directory(".", "index.html")


@app.after_request
def disable_caching(response):
    # Браузеры любят запоминать (кэшировать) css/js файлы и не скачивать их
    # заново, даже если мы их поправили. Пока сайт активно дорабатывается,
    # это мешает: правки как будто "не применяются". Эта функция добавляет
    # к каждому ответу сервера заголовок, который запрещает браузеру
    # сохранять файлы в кэш — при каждом обновлении страницы всё будет
    # подгружаться заново, свежим.
    response.headers["Cache-Control"] = "no-store"
    return response


# Этот блок выполняется, только если запустить файл напрямую
# командой "python3 app.py" (а не импортировать его из другого файла).
if __name__ == "__main__":
    app.run(debug=True, port=5050)
